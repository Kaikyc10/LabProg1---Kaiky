public class A4_AG2_AprovacaoAluno {
    public static void main(String[] args) {
        double media = 7.5;
        int faltas = 20;

        if(media >=7 && faltas <=25){
            System.out.println("Aluno aprovado!");
        }else{
            System.out.println("Aluno reprovado.");
        }

        // && = E
        // || = OU
        // ! = Negação lógica
    }
}
